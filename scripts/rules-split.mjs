#!/usr/bin/env node
// Splits MASTER_PROMPT_FINAL.md into one file per «## N.» section under docs/rules/ plus docs/rules/INDEX.md,
// so a session reads only the section it needs (CLAUDE.md «Models (token economy)»). The master stays the single
// source of rules: docs/rules/ is generated, never edited by hand.
//   node scripts/rules-split.mjs            write docs/rules/
//   node scripts/rules-split.mjs --check    exit 1 if docs/rules/ is out of sync with the master (CI)
//   node scripts/rules-split.mjs --selftest prove --check catches a stale or a missing section
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

export function split(text) {
  const lines = text.split('\n');
  const files = {};
  const index = [];
  let head = [];
  let cur = null;
  let inFence = false;
  const flush = () => {
    if (cur) files[cur.name] = cur.lines.join('\n').replace(/\n+$/, '') + '\n';
  };
  for (const line of lines) {
    if (/^```/.test(line)) inFence = !inFence;
    const m = !inFence && line.match(/^## (\d+)\.\s+(.*)$/);
    if (m) {
      flush();
      const num = m[1].padStart(2, '0');
      const name = `${num}.md`;
      cur = { name, lines: [GEN, line] };
      index.push({ name, num: m[1], title: m[2], subs: [] });
      continue;
    }
    if (!cur) {
      head.push(line);
      continue;
    }
    cur.lines.push(line);
    const s = !inFence && line.match(/^### (\d+\.\d+)\.?\s+(.*)$/);
    if (s) index[index.length - 1].subs.push(`§${s[1]} ${s[2]}`);
  }
  flush();
  files['00-intro.md'] = GEN + head.join('\n').replace(/\n+$/, '') + '\n';
  const kb = (n) => (Buffer.byteLength(files[n]) / 1024).toFixed(1);
  const idx = [
    GEN.trimEnd(),
    '# Правила по разделам (оглавление MASTER_PROMPT_FINAL.md)',
    '',
    'Читайте только нужный раздел. Размер — для оценки токенов (~1 КБ ≈ 300 токенов).',
    '',
    `- [00-intro.md](00-intro.md) — вступление (${kb('00-intro.md')} КБ)`,
    ...index.map(
      (e) =>
        `- [${e.name}](${e.name}) — §${e.num} ${e.title} (${kb(e.name)} КБ)` +
        (e.subs.length ? `\n  - ${e.subs.join('\n  - ')}` : ''),
    ),
    '',
  ].join('\n');
  files['INDEX.md'] = idx;
  return files;
}

const GEN = '<!-- generated by scripts/rules-split.mjs from MASTER_PROMPT_FINAL.md; do not edit -->\n';

function diff(dir, files) {
  const problems = [];
  const have = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.md')) : [];
  for (const [n, body] of Object.entries(files)) {
    const p = path.join(dir, n);
    if (!fs.existsSync(p)) problems.push(`missing ${n}`);
    else if (fs.readFileSync(p, 'utf8') !== body) problems.push(`stale ${n}`);
  }
  for (const n of have) if (!(n in files)) problems.push(`extra ${n}`);
  return problems;
}

function write(dir, files) {
  fs.mkdirSync(dir, { recursive: true });
  for (const n of fs.readdirSync(dir)) if (n.endsWith('.md') && !(n in files)) fs.unlinkSync(path.join(dir, n));
  for (const [n, body] of Object.entries(files)) fs.writeFileSync(path.join(dir, n), body);
}

function main() {
  const args = process.argv.slice(2);
  const dir = path.join(ROOT, 'docs/rules');
  const master = fs.readFileSync(path.join(ROOT, 'MASTER_PROMPT_FINAL.md'), 'utf8');
  if (args.includes('--selftest')) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'rules-'));
    const files = split(master);
    write(tmp, files);
    const ok = diff(tmp, files).length === 0;
    const stale = diff(tmp, split(master + '\nextra line\n')).some((p) => p.startsWith('stale'));
    const missing = diff(tmp, split(master + '\n## 99. Новый раздел\n')).some((p) => p.startsWith('missing'));
    const joined = Object.keys(files)
      .filter((n) => n !== 'INDEX.md')
      .sort()
      .map((n) => files[n].replace(GEN, ''))
      .join('\n');
    const lost = master.split('\n').filter((l) => l.trim() && !joined.includes(l));
    fs.rmSync(tmp, { recursive: true, force: true });
    const res = { inSync: ok, catchesStale: stale, catchesMissing: missing, linesLost: lost.length };
    console.log('rules-split selftest', JSON.stringify(res));
    process.exit(ok && stale && missing && lost.length === 0 ? 0 : 1);
  }
  const files = split(master);
  if (args.includes('--check')) {
    const p = diff(dir, files);
    if (p.length) {
      console.error(`docs/rules out of sync with MASTER_PROMPT_FINAL.md: ${p.join(', ')}\nrun: node scripts/rules-split.mjs`);
      process.exit(1);
    }
    console.log(`docs/rules in sync (${Object.keys(files).length} files)`);
    return;
  }
  write(dir, files);
  console.log(`wrote docs/rules (${Object.keys(files).length} files)`);
}

main();
