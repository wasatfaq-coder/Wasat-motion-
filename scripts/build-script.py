def words(t):
    return re.sub(r"\[[^\]]+\]", " ", t).split()

out = {"topic": "Почему нам кажется, что время течёт быстро", "targetDurationSec": 105,
       "wordsPerSec": 2.3, "hookCandidates": hooks, "selectedHook": "A", "scenes": []}
total = 0
for sid, purpose, src, disp, tts, beats in S:
    d = [x.strip() for x in disp.split(" / ")]
    t = [x.strip() for x in tts.split(" / ")]
    assert len(d) == len(t), sid
    for a, b in zip(d, t):
        na, nb = [w.lower().strip('.,:;—?!«»') for w in words(a)], [w.lower().strip('.,:;—?!«»') for w in words(b)]
        assert na == nb, (sid, a, b)
        assert 1 <= len(words(a)) <= 6, (sid, a)
    n = sum(len(words(x)) for x in d)
    total += n
    alltext = " ".join(d)
    for bid, w in beats:
        assert w in alltext, (sid, w)
    out["scenes"].append({"id": sid, "purpose": purpose, "source": src, "words": n,
        "estSec": round(n / 2.3, 1),
        "fragments": [{"display": a, "tts": b} for a, b in zip(d, t)],
        "beats": [{"id": b, "word": w} for b, w in beats]})
out["totalWords"] = total
out["estDurationSec"] = round(total / 2.3 + len(S) * 0.6, 1)
(root / "content" / "script.json").write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
for s in out["scenes"]:
    print(s["id"], s["words"], s["estSec"])
print("total", total, "est", out["estDurationSec"])
